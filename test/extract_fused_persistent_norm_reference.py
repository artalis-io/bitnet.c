"""Freeze final three-input RMSNorm from the original in-place compiled cubin.
Usage: python3 extract_fused_persistent_norm_reference.py CUBIN OUTPUT.h
Pin CUDA_VISIBLE_DEVICES to the authorized device. No native kernels are used.
Norm hashes come from the original cubin; residual hashes from scalar CPU F32
addition with one final BF16 rounding. The native API remains disjoint.
"""
from pathlib import Path
import hashlib
import json
import subprocess
import sys
import tempfile
cubin = Path(sys.argv[1]); output = Path(sys.argv[2])
# This fixture admits exactly the independently inspected stock final kernel.
assert hashlib.sha256(cubin.read_bytes()).hexdigest() == '2849d9b2b76133acee676a7ab1cea9ad2139c65d4a2a2fe4fa0f925dd13033ea'
source = r'''

#include <cuda_runtime.h>
#include <cuda.h>
#include <cassert>
#include <cstdio>
#include <cstdlib>
#include <cstdint>
#include <cstring>
#include <cmath>
static uint16_t bf(float v){uint32_t b;memcpy(&b,&v,4);return(uint16_t)((b+0x7fff+((b>>16)&1))>>16);}
static float fp(uint16_t b){uint32_t v=(uint32_t)b<<16;float f;memcpy(&f,&v,4);return f;}
static uint64_t hash(const uint16_t*p,size_t n){uint64_t h=UINT64_C(14695981039346656037);for(size_t i=0;i<n;i++){h=(h^(p[i]&255))*UINT64_C(1099511628211);h=(h^(p[i]>>8))*UINT64_C(1099511628211);}return h;}
int main(){assert(cudaSetDevice(0)==cudaSuccess&&cuInit(0)==CUDA_SUCCESS);
CUmodule mod;CUfunction fun;
assert(cuModuleLoad(&mod,FILE)==CUDA_SUCCESS&&cuModuleGetFunction(&fun,mod,NAME)==CUDA_SUCCESS);
int counts[]={1,5,17,129,1025};
printf("/* Original selected cubins; generated by extract_fused_persistent_norm_reference.py. */\n");
printf("typedef struct {int seed,tokens,kind,reduction;uint64_t norm,residual;} BnFusedPersistentNormReference;\nstatic const BnFusedPersistentNormReference cuda_fused_persistent_norm_cases[]={\n");
for(int seed=0;seed<8;seed++)for(int nt:counts){size_t n=(size_t)nt*5120;uint16_t*h[4],*out=(uint16_t*)malloc(n*2),*sum=(uint16_t*)malloc(n*2);void*d[6];for(int i=0;i<6;i++)assert(cudaMalloc(&d[i],n*2)==cudaSuccess);
for(int input=0;input<4;input++){size_t count=input==3?5120:n;h[input]=(uint16_t*)malloc(count*2);assert(h[input]);for(size_t i=0;i<count;i++){
float value=(float)((int)((i*37+i/13+input*173+seed*11)%1009)-504)/128.0f;
if(seed==1&&input<3&&i%16==0)value=input==0?16777216.0f:input==1?-16777216.0f:0.00390625f;
if(seed==2)value*=0.000030517578125f;if(seed==3)value*=128.0f;
if(seed==4)value=ldexpf((float)((int)(i%127)-63),-60+(int)(i%61));
if(seed==5){unsigned u=(unsigned)(i*2654435761u+input*2246822519u+12345u);value=ldexpf((float)((int)(u%255)-127)/128.0f,(int)((u>>8)%81)-40);}
if(seed==6){value=ldexpf((float)((int)(i%127)-63),(int)(i%101)-50);if(input==1)value=-value;if(input==2)value=0.0009765625f;}
if(seed==7)value=ldexpf((float)((int)(i%63)-31)/32.0f,(int)(i%121)-60);
if(input==3)value=(float)((int)(i%63)-31)/32.0f;h[input][i]=bf(value);}
assert(cudaMemcpy(d[input],h[input],count*2,cudaMemcpyHostToDevice)==cudaSuccess);}
// Original final norm mutates hidden; map hidden=h[2], block=h[0], residual=h[1].
// Native sum is F32(block+residual)+hidden, then rounded once to BF16.
int cols=5120;void*scratch=NULL;
void*args[]={&d[2],&d[0],&d[1],&d[3],&nt,&cols,&scratch,&scratch};
assert(cuLaunchKernel(fun,nt,1,1,512,1,1,64,0,args,NULL)==CUDA_SUCCESS);
assert(cudaMemcpy(out,d[2],n*2,cudaMemcpyDeviceToHost)==cudaSuccess);
for(size_t i=0;i<n;i++){volatile float first=fp(h[0][i])+fp(h[1][i]);sum[i]=bf(first+fp(h[2][i]));}
printf("{%d,%d,2,6,UINT64_C(%llu),UINT64_C(%llu)},\n",seed,nt,(unsigned long long)hash(out,n),(unsigned long long)hash(sum,n));
for(int i=0;i<6;i++)cudaFree(d[i]);for(int i=0;i<4;i++)free(h[i]);free(out);free(sum);
}printf("};\n");return 0;}

'''
source = source.replace('FILE', json.dumps(str(cubin))).replace('NAME', json.dumps(cubin.stem))
with tempfile.TemporaryDirectory() as tmp:
    cpp = Path(tmp)/'reference.cu'; binary = Path(tmp)/'reference'
    cpp.write_text(source)
    subprocess.run(['/usr/local/cuda/bin/nvcc','-O3','-std=c++11',str(cpp),'-lcuda','-o',str(binary)],check=True)
    result = subprocess.check_output([str(binary)],text=True)
output.write_text('/* Original final in-place3 cubin SHA-256: '+hashlib.sha256(cubin.read_bytes()).hexdigest()+' */\n'+result)
print(output, hashlib.sha256(output.read_bytes()).hexdigest())
