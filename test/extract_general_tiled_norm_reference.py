"""Freeze independent original compiled RMS outputs. No native kernels.
Usage: python3 extract_general_tiled_norm_reference.py INDUCTOR_CACHE OUTPUT.h
Requires nvcc, CUDA driver, and the original cache's selected cubins.
The caller must pin CUDA_VISIBLE_DEVICES to its authorized test device.
"""
from pathlib import Path
import hashlib
import json
import re
import subprocess
import sys
import tempfile
root = Path(sys.argv[1]); output = Path(sys.argv[2]); selected = {}
for config in root.rglob('*.best_config'):
    d = json.loads(config.read_text())
    cache_hash = d.get('triton_cache_hash')
    if not cache_hash: continue
    for ptx in (root/'triton/0'/cache_hash).glob('*.ptx'):
        s = ptx.read_text(); head = s[s.find('.entry'):s.find(')',s.find('.entry'))]
        if 'rms' not in head: continue
        location = re.search(r'// (c[a-z0-9]+\.py):',s)
        assert location, ptx
        original_source = next(root.rglob(location.group(1))).read_text()
        # In-place three-input norms have the same pointer count as ordinary
        # two-input norms. They mutate an operand and cannot supply this oracle.
        if 'in_out_ptr' in original_source: continue
        pointers = len(re.findall(r'\.param\s+\.u64',head))
        key = (pointers,d.get('R0_BLOCK'))
        if key in [(5,8192),(6,8192),(6,1024),(8,8192),(8,1024)]:
            selected.setdefault(key,ptx)
keys = [(5,8192),(6,8192),(6,1024),(8,8192),(8,1024)]
assert all(k in selected for k in keys)
files = [selected[k].with_suffix('.cubin') for k in keys]
metadata = [json.loads(selected[k].with_suffix('.json').read_text()) for k in keys]
source = r'''
#include <cuda_runtime.h>
#include <cuda.h>
#include <cassert>
#include <cstdio>
#include <cstdlib>
#include <cstdint>
#include <cstring>
#include <cmath>
static uint16_t bf(float v){uint32_t b;memcpy(&b,&v,4);return(uint16_t)((b+0x7fff+((b>>16)&1))>>16);}
static float fp(uint16_t b){uint32_t v=(uint32_t)b<<16;float f;memcpy(&f,&v,4);return f;}
static uint64_t hash(const uint16_t*p,size_t n){uint64_t h=UINT64_C(14695981039346656037);for(size_t i=0;i<n;i++){h=(h^(p[i]&255))*UINT64_C(1099511628211);h=(h^(p[i]>>8))*UINT64_C(1099511628211);}return h;}
int main(){assert(cudaSetDevice(0)==cudaSuccess&&cuInit(0)==CUDA_SUCCESS);
const char*files[]=FILES;const char*names[]=NAMES;int shared[]=SHARED;
CUmodule mods[5];CUfunction fun[5];for(int i=0;i<5;i++){assert(cuModuleLoad(&mods[i],files[i])==CUDA_SUCCESS&&cuModuleGetFunction(&fun[i],mods[i],names[i])==CUDA_SUCCESS);}
int counts[]={1,5,17,129,257};
printf("/* Original selected cubins; generated by extract_general_tiled_norm_reference.py. */\n");
printf("typedef struct {int seed,tokens,kind,reduction;uint64_t norm,residual;} BnGeneralNormReference;\nstatic const BnGeneralNormReference cuda_general_norm_cases[]={\n");
for(int seed=0;seed<8;seed++)for(int nt:counts){size_t n=(size_t)nt*5120;uint16_t*h[4],*out=(uint16_t*)malloc(n*2),*sum=(uint16_t*)malloc(n*2);void*d[6];for(int i=0;i<6;i++)assert(cudaMalloc(&d[i],n*2)==cudaSuccess);
for(int input=0;input<4;input++){size_t count=input==3?5120:n;h[input]=(uint16_t*)malloc(count*2);assert(h[input]);for(size_t i=0;i<count;i++){
float value=(float)((int)((i*37+i/13+input*173+seed*11)%1009)-504)/128.0f;
if(seed==1&&input<3&&i%16==0)value=input==0?16777216.0f:input==1?-16777216.0f:0.00390625f;
if(seed==2)value*=0.000030517578125f;if(seed==3)value*=128.0f;
if(seed==4)value=ldexpf((float)((int)(i%127)-63),-60+(int)(i%61));
if(seed==5){unsigned u=(unsigned)(i*2654435761u+input*2246822519u+12345u);value=ldexpf((float)((int)(u%255)-127)/128.0f,(int)((u>>8)%81)-40);}
if(seed==6){value=ldexpf((float)((int)(i%127)-63),(int)(i%101)-50);if(input==1)value=-value;if(input==2)value=0.0009765625f;}
if(seed==7)value=ldexpf((float)((int)(i%63)-31)/32.0f,(int)(i%121)-60);
if(input==3)value=(float)((int)(i%63)-31)/32.0f;h[input][i]=bf(value);}
assert(cudaMemcpy(d[input],h[input],count*2,cudaMemcpyHostToDevice)==cudaSuccess);}
for(int mode=0;mode<5;mode++){int kind=mode==0?0:mode<3?1:2;void*scratch=NULL;int cols=5120;void*plain[]={&d[0],&d[3],&d[4],&nt,&cols,&scratch,&scratch};void*two[]={&d[0],&d[1],&d[3],&d[4],&nt,&cols,&scratch,&scratch};void*three[]={&d[2],&d[0],&d[1],&d[3],&d[5],&d[4],&nt,&cols,&scratch,&scratch};void**args=kind==0?plain:kind==1?two:three;
assert(cuLaunchKernel(fun[mode],nt,1,1,mode==2||mode==4?256:512,1,1,shared[mode],0,args,NULL)==CUDA_SUCCESS);assert(cudaMemcpy(out,d[4],n*2,cudaMemcpyDeviceToHost)==cudaSuccess);
uint64_t sh=0;if(kind==2){assert(cudaMemcpy(sum,d[5],n*2,cudaMemcpyDeviceToHost)==cudaSuccess);sh=hash(sum,n);}else if(kind==1){for(size_t i=0;i<n;i++)sum[i]=bf(fp(h[0][i])+fp(h[1][i]));sh=hash(sum,n);}
printf("{%d,%d,%d,%d,UINT64_C(%llu),UINT64_C(%llu)},\n",seed,nt,kind,mode==2||mode==4?5:4,(unsigned long long)hash(out,n),(unsigned long long)sh);
}
for(int i=0;i<6;i++)cudaFree(d[i]);for(int i=0;i<4;i++)free(h[i]);free(out);free(sum);
}printf("};\n");return 0;}
'''
source = source.replace('FILES','{'+','.join(json.dumps(str(f))for f in files)+'}')
source = source.replace('NAMES','{'+','.join(json.dumps(selected[k].stem)for k in keys)+'}')
source = source.replace('SHARED','{'+','.join(str(d['shared'])for d in metadata)+'}')
with tempfile.TemporaryDirectory() as tmp:
    cpp=Path(tmp)/'reference.cu'; binary=Path(tmp)/'reference'; cpp.write_text(source)
    subprocess.run(['/usr/local/cuda/bin/nvcc','-O3','-std=c++11',str(cpp),'-lcuda','-o',str(binary)],check=True)
    result=subprocess.check_output([str(binary)],text=True)
provenance='/* Cubin SHA-256, in plain/P2/L2/P3/L3 order:\n'+''.join(' * '+hashlib.sha256(f.read_bytes()).hexdigest()+'\n'for f in files)+' */\n'
output.write_text(provenance+result)
print(output,hashlib.sha256(output.read_bytes()).hexdigest())
